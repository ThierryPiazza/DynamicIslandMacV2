#!/bin/bash
set -euo pipefail
project_dir="$(cd "$(dirname "$0")/.." && pwd)"
bridge_dir="${DYNAMICISLAND_ZEN_STATE_DIRECTORY:-$HOME/Library/Application Support/DynamicIsland/ZenBridge}"
manifest_dir="${DYNAMICISLAND_ZEN_MANIFEST_DIRECTORY:-$HOME/Library/Application Support/Mozilla/NativeMessagingHosts}"
mkdir -p "$bridge_dir" "$manifest_dir"
chmod 700 "$bridge_dir"
xcrun swiftc -O "$project_dir/DynamicIslandV2/System/ZenMediaSnapshot.swift" "$project_dir/Scripts/ZenBridge/main.swift" -o "$bridge_dir/zen-native-host.new"
chmod 700 "$bridge_dir/zen-native-host.new"
mv "$bridge_dir/zen-native-host.new" "$bridge_dir/zen-native-host"
/usr/bin/plutil -create xml1 "$manifest_dir/com.thierrypiazza.dynamicisland.zen.json.new"
/usr/bin/plutil -insert name -string com.thierrypiazza.dynamicisland.zen "$manifest_dir/com.thierrypiazza.dynamicisland.zen.json.new"
/usr/bin/plutil -insert description -string 'DynamicIsland Zen media bridge' "$manifest_dir/com.thierrypiazza.dynamicisland.zen.json.new"
/usr/bin/plutil -insert path -string "$bridge_dir/zen-native-host" "$manifest_dir/com.thierrypiazza.dynamicisland.zen.json.new"
/usr/bin/plutil -insert type -string stdio "$manifest_dir/com.thierrypiazza.dynamicisland.zen.json.new"
/usr/bin/plutil -insert allowed_extensions -json '["zen-macos-timeline-fix@local.invalid"]' "$manifest_dir/com.thierrypiazza.dynamicisland.zen.json.new"
/usr/bin/plutil -convert json "$manifest_dir/com.thierrypiazza.dynamicisland.zen.json.new"
mv "$manifest_dir/com.thierrypiazza.dynamicisland.zen.json.new" "$manifest_dir/com.thierrypiazza.dynamicisland.zen.json"
printf 'Host installato: %s\nCarica Extensions/ZenTimeline/manifest.json da about:debugging in Zen.\n' "$bridge_dir/zen-native-host"
